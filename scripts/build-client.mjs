/**
 * Build the browser bundle: esbuild (CJS emit so external requires keep the
 * exact require("react") shape the shell's module loader resolves), then wrap
 * the output in the window.__ModuleLoader__.load handoff the client-modules
 * host serves verbatim at /plugins/dsh-workspace-time-travel/client.js.
 */
import { build } from 'esbuild'
import { readFileSync, writeFileSync, rmSync } from 'node:fs'

const outfile = 'lib/client.raw.js'
await build({
  entryPoints: ['src/client/index.tsx'],
  outfile,
  bundle: true,
  format: 'cjs',
  platform: 'node',
  target: 'es2020',
  jsx: 'automatic',
  external: ['react', 'react/jsx-runtime'],
  logLevel: 'info',
  minify: false,
})
const raw = readFileSync(outfile, 'utf8')
const body = raw.split('\n').map((line) => (line.length > 0 ? '\t\t' + line : '')).join('\n')
const head = [
  '/**',
  ' * dsh-workspace-time-travel - browser bundle (generated by scripts/build-client.mjs;',
  ' * do not edit). Wrapped in the window.__ModuleLoader__.load handoff the',
  ' * client-modules host serves verbatim at /plugins/dsh-workspace-time-travel/client.js.',
  ' */',
  'window.__ModuleLoader__.load({',
  "	id: 'dsh-workspace-time-travel',",
  '	factory: (require) => {',
  '		var module = { exports: {} };',
  '		var exports = module.exports;',
  "\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: 'Module' });",
].join('\n')
const tail = [
  '		return module.exports;',
  '	}',
  '});',
  '',
].join('\n')
writeFileSync('lib/client.js', head + '\n' + body + '\n' + tail)
rmSync(outfile)
console.log('built lib/client.js (' + (head.length + body.length + tail.length) + ' bytes)')

